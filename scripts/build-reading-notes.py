#!/usr/bin/env python3
"""Render the static reading journal. Run from any directory; no dependencies."""
from pathlib import Path
from datetime import date
from html import escape as e
import re
import sys
import unicodedata
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
GENERATED = '<!-- Generated by scripts/build-reading-notes.py; edit reading-notes/entries/*.md. -->'
DATE_FILE = re.compile(r'\d{4}-\d{2}-\d{2}\.md$')
ARTICLE = re.compile(r'^##\s+\[(.+)\]\((https?://\S+)\)(?:\s+\{#([a-z0-9][a-z0-9-]*)\})?\s*$')
BULLET = re.compile(r'^[-*+]\s+(.+)$')
INLINE = re.compile(r'`([^`\n]+)`|\*\*([^*\n]+)\*\*|\*([^*\n]+)\*|\[([^\]\n]+)\]\((https?://[^\s)]+)\)')


def web_url(value):
    parsed = urlsplit(value)
    if parsed.scheme not in ('http', 'https') or not parsed.netloc or parsed.username or parsed.password:
        raise ValueError('Use a complete http:// or https:// source URL without embedded credentials.')
    return value


def inline_markdown(value):
    """Small, escaped inline subset: emphasis, code, and http(s) links."""
    parts, end = [], 0
    for match in INLINE.finditer(value):
        parts.append(e(value[end:match.start()]))
        code, bold, italic, label, url = match.groups()
        if code is not None:
            parts.append(f'<code>{e(code)}</code>')
        elif bold is not None:
            parts.append(f'<strong>{e(bold)}</strong>')
        elif italic is not None:
            parts.append(f'<em>{e(italic)}</em>')
        else:
            parts.append(f'<a href="{e(web_url(url))}" target="_blank" rel="noopener noreferrer">{e(label)}</a>')
        end = match.end()
    parts.append(e(value[end:]))
    return ''.join(parts)


def slug(value):
    ascii_value = unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]+', '-', ascii_value.lower()).strip('-') or 'reading'


def parse_day(path):
    """Read the documented journal Markdown format; report mistakes by line."""
    try:
        day_date = date.fromisoformat(path.stem).isoformat()
    except ValueError as exc:
        raise ValueError(f'{path.name}: use a YYYY-MM-DD.md filename with a valid date.') from exc
    day = {'date': day_date, 'notes': []}
    note = None
    seen_ids = set()

    def fail(number, message):
        raise ValueError(f'{path.name}:{number}: {message}')

    def finish(number):
        nonlocal note
        if note is None:
            return
        if not note['jottings']:
            fail(number, 'Add at least one bullet beneath this reading.')
        day['notes'].append(note)
        note = None

    lines = path.read_text(encoding='utf-8-sig').splitlines()
    for number, raw in enumerate(lines, 1):
        line = raw.strip()
        if line.startswith(('```', '~~~')):
            fail(number, 'Use inline backticks for code; fenced code blocks are not supported.')
        if not line or line == '---' or (line.startswith('<!--') and line.endswith('-->')):
            continue
        heading = ARTICLE.fullmatch(line)
        if heading:
            finish(number)
            title, url, custom_id = heading.groups()
            try:
                web_url(url)
            except ValueError as exc:
                fail(number, str(exc))
            base = custom_id or slug(title)
            entry_id = base
            suffix = 2
            if custom_id and custom_id in seen_ids:
                fail(number, f'Duplicate anchor: {custom_id}')
            while entry_id in seen_ids:
                entry_id = f'{base}-{suffix}'
                suffix += 1
            seen_ids.add(entry_id)
            source = urlsplit(url).hostname.removeprefix('www.')
            note = {'id': entry_id, 'title': title, 'url': url, 'source': source, 'jottings': []}
            continue
        if line.startswith('##'):
            fail(number, 'Use ## [Article title](https://original-url) for each reading.')
        if line.startswith('# '):
            if day['notes'] or note is not None or 'title' in day:
                fail(number, 'An optional # Day title belongs once, before the readings.')
            day['title'] = line[2:].strip()
            continue
        if note is None:
            fail(number, 'Start a reading with ## [Article title](https://original-url).')
        bullet = BULLET.fullmatch(line)
        if bullet:
            if raw[:1].isspace():
                fail(number, 'Nested lists are not supported; keep each note as a top-level bullet.')
            note['jottings'].append(bullet.group(1))
            continue
        if raw[:1].isspace() and note['jottings']:
            note['jottings'][-1] += ' ' + line
            continue
        if note['jottings']:
            fail(number, 'Start another note with "- ", or indent a wrapped bullet.')
        if note.get('_has_source'):
            fail(number, 'Only one source line is allowed before the bullet notes.')
        if '|' in line:
            source, raw_date = (part.strip() for part in line.rsplit('|', 1))
            metadata = re.fullmatch(r'(?:(updated|data through|published)\s+)?(\d{4}-\d{2}-\d{2})', raw_date, re.I)
            if not source or metadata is None:
                fail(number, 'Use Source name | YYYY-MM-DD (or Source name | updated YYYY-MM-DD).')
            label, value = metadata.groups()
            try:
                date.fromisoformat(value)
            except ValueError:
                fail(number, f'Invalid source date: {value}')
            note['source_date'] = value
            if label and label.lower() != 'published':
                note['date_label'] = label.lower()
            note['source'] = source
        else:
            note['source'] = line
        note['_has_source'] = True
    finish(len(lines) + 1)
    if not day['notes']:
        fail(1, 'Add at least one reading before building this file.')
    for entry in day['notes']:
        entry.pop('_has_source', None)
    return day


def load_days(root):
    paths = sorted((root / 'reading-notes' / 'entries').glob('*.md'), reverse=True)
    for path in paths:
        if not DATE_FILE.fullmatch(path.name):
            raise ValueError(f'{path.name}: entries must be named YYYY-MM-DD.md; keep templates outside entries/.')
    if not paths:
        raise ValueError('Add a YYYY-MM-DD.md file in reading-notes/entries first.')
    return [parse_day(path) for path in paths]

def long_date(value):
    d = date.fromisoformat(value)
    return f'{d:%B} {d.day}, {d.year}'

def note_body(note):
    return '<ul class="reading-jottings">' + ''.join(f'<li>{inline_markdown(line)}</li>' for line in note['jottings']) + '</ul>'


def render_day(day):
    d = day['date']
    notes = []
    for n in day['notes']:
        citation = e(n['source'])
        if n.get('source_date'):
            source_date = date.fromisoformat(n['source_date'])
            short_date = f'{source_date:%b} {source_date.day}'
            if source_date.year != date.fromisoformat(d).year:
                short_date += f', {source_date.year}'
            prefix = f'{n["date_label"]} ' if n.get('date_label') else ''
            citation += f', {e(prefix)}<time datetime="{n["source_date"]}">{short_date}</time>'
        notes.append(f'''<article class="reading-entry" id="{e(d)}-{e(n['id'])}">
          <h3><a href="{e(n['url'])}" target="_blank" rel="noopener noreferrer">{e(n['title'])} <span aria-hidden="true">↗</span><span class="sr-only"> (opens in a new tab)</span></a></h3>
          <p class="reading-source">{citation}</p>
          {note_body(n)}
        </article>''')
    return f'''<section class="reading-day" aria-labelledby="day-{d}">
      <div class="reading-dayheading"><h2 id="day-{d}"><a href="{d}.html"><time datetime="{d}">{long_date(d)}</time></a></h2><span>{date.fromisoformat(d):%A}</span></div>
      {''.join(notes)}
    </section>'''

def page(days, selected=None):
    visible = [selected] if selected else days
    title = f'Research Journal — {long_date(selected["date"])}' if selected else 'Research Journal'
    description = f'Research journal for {long_date(selected["date"])} by Shivam Sharma.' if selected else 'Blogs, papers and articles I found interesting with some of my notes on them'
    path = f'{selected["date"]}.html' if selected else 'index.html'
    blog_dates = ''
    for day in days:
        current = ' aria-current="page"' if selected and selected['date'] == day['date'] else ''
        blog_dates += f'<li><a href="{day["date"]}.html"{current}><time datetime="{day["date"]}">{long_date(day["date"])}</time></a></li>'
    previous_next = ''
    if selected:
        i = days.index(selected)
        if i + 1 < len(days): previous_next += f'<a href="{days[i+1]["date"]}.html">← Older entry</a>'
        if i > 0: previous_next += f'<a href="{days[i-1]["date"]}.html">Newer entry →</a>'
    return f'''<!doctype html>
{GENERATED}
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)} — Shivam Sharma</title><meta name="description" content="{e(description)}">
<link rel="canonical" href="https://iamshiv.ai/reading-notes/{path}">
<meta property="og:title" content="{e(title)} — Shivam Sharma"><meta property="og:description" content="{e(description)}"><meta property="og:type" content="{'article' if selected else 'website'}"><meta property="og:url" content="https://iamshiv.ai/reading-notes/{path}">
<link rel="icon" href="../images/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="../stylesheet.css"><link rel="stylesheet" href="../project-overrides.css"><link rel="stylesheet" href="../mineral-blue.css"><link rel="stylesheet" href="../reading-notes.css">
</head>
<body id="top"><a class="skip-link" href="#main">Skip to content</a>
<header class="site-header"><div class="wrap nav-wrap"><a class="wordmark" href="../index.html" aria-label="Shivam Sharma home">Hi! I am Shiv</a><nav aria-label="Primary navigation"><a href="../index.html">Home</a><a href="../publications.html">Publications</a><a href="../background.html">Background</a><a aria-current="page" href="index.html">Research Journal</a><a href="../Shivam_Resume.pdf" target="_blank" rel="noopener">CV <span aria-hidden="true">↗</span></a></nav></div></header>
<main id="main" class="reading-wrap">
  <header class="reading-hero"><h1><a href="index.html">Research Journal<span>.</span></a></h1><p>Blogs, papers and articles I found interesting with some of my notes on them</p></header>
  <div class="reading-layout">
    <aside class="reading-sidebar" aria-label="Research journal navigation"><details class="reading-blog-index" open><summary>Blogs</summary><nav class="reading-blog-list" aria-label="Blog dates" tabindex="0"><ul>{blog_dates}</ul></nav></details></aside>
    <div class="reading-content">{''.join(render_day(d) for d in visible)}<nav class="reading-pagination" aria-label="Reading entry navigation">{previous_next}<a href="#top">Back to top ↑</a></nav></div>
  </div>
</main><footer><div class="wrap footer-wrap"><p>© {date.fromisoformat(days[0]['date']).year} Shivam Sharma</p><p>Research Journal</p></div></footer></body></html>
'''


def build(root=ROOT):
    # Parse every entry before writing, so a malformed file cannot partially rebuild the site.
    days = load_days(root)
    out = root / 'reading-notes'
    outputs = {out / 'index.html': page(days)}
    outputs.update({out / f'{day["date"]}.html': page(days, day) for day in days})
    for path, content in outputs.items():
        path.write_text(content, encoding='utf-8')
    # Only remove old pages carrying this builder's marker; preserve hand-authored files.
    for path in out.glob('????-??-??.html'):
        if path not in outputs and GENERATED in path.read_text(encoding='utf-8'):
            path.unlink()
    print(f'Built research journal from {len(days)} Markdown day(s).')


if __name__ == '__main__':
    try:
        build()
    except ValueError as exc:
        print(f'Research journal: {exc}', file=sys.stderr)
        raise SystemExit(1)
